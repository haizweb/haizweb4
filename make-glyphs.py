#!/usr/bin/env python3
"""
Extracts the outlines of the digits 0-9 from the (variable) Montserrat font at a
given weight and writes them as a small ES module (src/gl/glyphs.js).

The outlines are used to build the applied 3D hour numerals of the watch dial.

usage:  python3 -I tools/make-glyphs.py <Montserrat[wght].ttf> <out.js> [weight]
"""
import sys
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
from fontTools.pens.svgPathPen import SVGPathPen

src, out = sys.argv[1], sys.argv[2]
weight = float(sys.argv[3]) if len(sys.argv) > 3 else 500

font = TTFont(src)
font = instancer.instantiateVariableFont(font, {"wght": weight})
gs = font.getGlyphSet()
cmap = font.getBestCmap()
upem = font["head"].unitsPerEm


def fmt(v):
    v = round(v, 1)
    return str(int(v)) if v == int(v) else str(v)


lines = []
for ch in "0123456789":
    name = cmap[ord(ch)]
    glyph = gs[name]
    pen = SVGPathPen(gs, ntos=fmt)
    glyph.draw(pen)
    d = pen.getCommands()
    lines.append(f'  "{ch}": {{ adv: {glyph.width / upem:.4f}, d: "{d}" }},')

with open(out, "w", encoding="utf-8") as fh:
    fh.write("// Generated by tools/make-glyphs.py from Montserrat (SIL OFL 1.1), weight %d.\n" % weight)
    fh.write("// Digit outlines in font units (1000 per em), y up. Do not edit by hand.\n")
    fh.write("export const UPEM = %d;\n" % upem)
    fh.write("export const GLYPHS = {\n")
    fh.write("\n".join(lines))
    fh.write("\n};\n")
print("wrote", out, "weight", weight)
